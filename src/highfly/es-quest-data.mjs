export function localizeQuestData(QUESTS,IDLE,CHAT,translate){
 let changed=0;
 for(const q of QUESTS){
  q.title=translate(q.title);q.verb=translate(q.verb);
  const es=QUEST_DIALOGUE_ES[q.id];
  if(!es)continue;
  for(const k of ['offer','wait','done']){
   if(!q[k])continue;
   if(!es[k]||q[k].length!==es[k].length)throw Error('Quest Spanish line drift: '+q.id+'.'+k);
   q[k]=[...es[k]];changed+=es[k].length;
  }
 }
 return changed;
}
