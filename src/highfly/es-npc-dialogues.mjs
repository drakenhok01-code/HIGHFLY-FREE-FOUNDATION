export function localizeNPCData(IDLE,CHAT){
 let count=0;
 for(const [id,entries] of Object.entries(NPC_IDLE_ES)){
  if(!IDLE[id]||IDLE[id].length!==entries.length)throw Error('Spanish NPC idle phase drift '+id);
  for(let i=0;i<entries.length;i++){
   const [phase,original]=IDLE[id][i],es=entries[i];
   if(original.length!==es.length)throw Error('Spanish NPC idle line drift '+id+':'+i);
   IDLE[id][i]=[phase,[...es]];count+=es.length;
  }
 }
 for(const [id,lines] of Object.entries(NPC_CHAT_ES)){
  if(!CHAT[id]||CHAT[id].length!==lines.length)throw Error('Spanish NPC chat drift '+id);
  CHAT[id]=[...lines];count+=lines.length;
 }
 return count;
}
