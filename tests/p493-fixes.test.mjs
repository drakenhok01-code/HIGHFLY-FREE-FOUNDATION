test('P493 no wallet loss on save and no item upgrades generated on loot or sale',()=>{
 const state=normalizeRpgState({items:{ore:3,training_shield:1},coins:40});
 const profession={inventory:{herb:4}};
 const before=state.gearTraits.bag.training_shield[0];
 assert.equal(before.plus,0);
 assert.equal(bagItemPrice('bag_upgrade'),0);
 assert.equal(transactBagItem(state,profession,'bag_upgrade','sell',1).ok,false);
 assert.equal(transactBagItem(state,profession,'training_shield','sell',2,0).ok,false);
 const one=transactBagItem(state,profession,'training_shield','sell',1,0);
 assert.equal(one.ok,true);
 assert.equal(state.gearTraits.bag.training_shield.length,0);
 assert.equal(state.items.training_shield,0);
 assert.equal(state.coins,40+one.earned);
 assert.equal(transactBagItem(state,profession,'herb','discard',2).ok,true);
 assert.equal(profession.inventory.herb,2);
 const remaining=transactBagItem(state,profession,'ore','sell',3);
 assert.equal(remaining.ok,true);
 assert.equal(state.items.ore,0);
 assert.equal(normalizeRpgState(state).coins,state.coins);
 assert.ok(Object.keys(ITEM_DEFS).includes('crab_shell'));
});
